// 既存生成試験の前提として、入力後に実UIの「設定確認」を明示操作する。
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

module.exports = async ({ run, until, wc, win }) => {
  await run("window.__rendererUI.resetConfiguration(); document.querySelector('[data-tab=output]').click()");
  assert.equal(await run("document.getElementById('generationGuideButton').disabled"), true);
  await run(`document.querySelector('.module-row[data-module-id=nginx]').click();
    document.querySelector('.module-row[data-module-id=nodejs]').click();
    document.querySelector('[data-tab=config]').click();`);
  const before = await run("window.ImageUI.selected('nodejs').image");
  assert.equal(await run("document.querySelector('[data-module-id=nodejs] .image-details').open"), false);
  assert.equal(await run("document.querySelector('[data-module-id=nodejs] .image-detail-text').checkVisibility()"), false);
  assert.doesNotMatch(await run("document.querySelector('[data-module-id=nodejs] .image-tag').textContent"), /sha256/);
  assert.doesNotMatch(await run("document.querySelector('[data-module-id=nodejs] .image-status').textContent"), /タグ確認：|保守情報確認：/);
  assert.match(await run("document.querySelector('[data-module-id=nodejs] .image-status').textContent"), /サポート中.*\n脆弱性未検査/s);
  await run(`document.querySelector('[data-module-id=nodejs] input[data-field-name=hostPort]').value = '3456';
    document.querySelector('[data-module-id=nodejs] .image-details summary').click();`);
  assert.equal(await run("document.querySelector('[data-module-id=nodejs] .image-details').open"), true);
  assert.match(await run("document.querySelector('[data-module-id=nodejs] .image-detail-text').textContent"), /sha256:.*\n.*digest：/s);
  await run("document.querySelector('[data-module-id=nodejs] .image-details summary').click()");
  assert.equal(await run("window.ImageUI.selected('nodejs').image"), before);
  assert.equal(await run("document.querySelector('[data-module-id=nodejs] input[data-field-name=hostPort]').value"), "3456");
  assert.equal(await run("getComputedStyle(document.querySelector('.sticky-executor')).position"), "static");
  await run("document.querySelector('[data-module-id=nodejs]').scrollIntoView()");
  assert.equal(await run("document.querySelector('.sticky-executor').getBoundingClientRect().bottom <= document.querySelector('section.card[data-module-id=nodejs]').getBoundingClientRect().top"), true);
  console.log("PASS collapsed version details preserve input/selection, important statuses remain visible, executor no longer overlaps");

  // 明示された互換入力は勝手に新しい既定値へ変換しない。
  await run(`document.querySelector('[data-module-id=nodejs] select[data-field-name=dataStoreType]').value = 'named';
    document.querySelector('[data-module-id=nodejs] select[data-field-name=dataStoreType]').dispatchEvent(new Event('change'));
    document.querySelector('[data-module-id=nodejs] input[data-field-name=startCmd]').value = 'npm install && npm run dev';
    document.querySelector('[data-module-id=nodejs] input[data-field-name=startCmd]').dispatchEvent(new Event('input'));
    window.__testConfirmModules(); window.__rendererGenerate.generateConfigs();`);
  assert.match(await run("document.querySelector('.node-runtime-notice').textContent"), /互換モード.*二重実行/s);
  assert.match(await run("document.getElementById('composeOutput').value"), /node-app:\/app/);
  await run(`document.querySelector('[data-module-id=nodejs] select[data-field-name=dataStoreType]').value = 'image';
    document.querySelector('[data-module-id=nodejs] select[data-field-name=dataStoreType]').dispatchEvent(new Event('change'));
    document.querySelector('[data-module-id=nodejs] input[data-field-name=startCmd]').value = 'npm run dev';
    window.__testConfirmModules(); window.__rendererGenerate.generateConfigs(); document.querySelector('[data-tab=output]').click();`);
  const compose = await run("document.getElementById('composeOutput').value");
  assert.doesNotMatch(compose, /node-app|npm install/);
  assert.match(compose, /3456:3000/);
  await run("document.getElementById('generationGuideButton').click()");
  assert.equal(await run("document.getElementById('generationGuideDialog').matches(':modal')"), true);
  assert.equal(await run("document.activeElement.id"), "generationGuideCloseButton");
  assert.equal(await run("document.querySelectorAll('#generationGuideDialog section').length"), 3);
  assert.match(await run("document.getElementById('guideStartup').textContent"), /docker compose config -q.*docker compose up --build -d.*docker compose logs.*docker compose stop/s);
  assert.match(await run("document.getElementById('guidePlacementNotes').textContent"), /build.context = .\/nodejs/);
  assert.match(await run("document.getElementById('guideSecurity').textContent"), /リバースプロキシはOFF/);
  assert.match(await run("document.getElementById('guideSecurity').textContent"), /3456:3000/);
  assert.match(await run("document.getElementById('generatedPlacementGuide').textContent"), /package-lock.json（利用者が準備）/);
  assert.equal(await run("document.getElementById('guideEditNotice').hidden"), true);
  assert.equal(await run("getComputedStyle(document.getElementById('guideScrollBody')).overflowY"), "auto");
  assert.ok(await run("document.getElementById('guideScrollBody').scrollHeight > document.getElementById('guideScrollBody').clientHeight"));
  const theme = await run("window.__rendererCore.getTheme()");
  const point = await run("(()=>{const r=document.getElementById('themeToggleButton').getBoundingClientRect();return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)}})()");
  wc.sendInputEvent({ type: "mouseDown", ...point, button: "left", clickCount: 1 });
  wc.sendInputEvent({ type: "mouseUp", ...point, button: "left", clickCount: 1 });
  assert.equal(await run("window.__rendererCore.getTheme()"), theme);
  wc.sendInputEvent({ type: "keyDown", keyCode: "Tab" }); wc.sendInputEvent({ type: "keyUp", keyCode: "Tab" });
  assert.equal(await run("document.getElementById('generationGuideDialog').contains(document.activeElement)"), true);
  wc.sendInputEvent({ type: "keyDown", keyCode: "Escape" }); wc.sendInputEvent({ type: "keyUp", keyCode: "Escape" });
  await until("!document.getElementById('generationGuideDialog').open");
  await until("document.activeElement.id === 'generationGuideButton'");
  assert.equal(await run("document.activeElement.id"), "generationGuideButton");
  await run("document.getElementById('generationGuideButton').click(); document.getElementById('generationGuideCloseButton').click()");
  assert.equal(await run("document.getElementById('generationGuideDialog').open"), false);
  console.log("PASS current-config guide sections, modal background protection, scrolling, keyboard focus, Escape and Close");

  // カード側だけ変更しても、ガイドは生成済みComposeと同じ版を説明する。
  await run(`document.querySelector('[data-module-id=nodejs] .image-series').value = '22';
    document.querySelector('[data-module-id=nodejs] .image-series').dispatchEvent(new Event('change'));
    document.getElementById('generationGuideButton').click();`);
  assert.ok((await run("document.getElementById('guideSecurity').textContent")).includes(before));
  await run("document.getElementById('generationGuideCloseButton').click(); document.getElementById('dockerfileOutput').value += '# manual edit'; document.getElementById('generationGuideButton').click()");
  assert.equal(await run("document.getElementById('guideEditNotice').hidden"), false);
  await run("document.getElementById('generationGuideCloseButton').click(); document.getElementById('dockerfileClearBtn').click(); document.getElementById('generationGuideButton').click()");
  assert.equal(await run("document.getElementById('guideEditNotice').hidden"), false);
  await run("document.getElementById('generationGuideCloseButton').click(); document.getElementById('composeClearBtn').click()");
  assert.equal(await run("document.getElementById('generationGuideButton').disabled"), true);
  assert.equal(await run("document.getElementById('guideSecurity').textContent"), "");
  await run("document.querySelector('.module-row[data-module-id=nodejs]').click(); window.__testConfirmModules(); window.__rendererGenerate.generateConfigs()");
  assert.doesNotMatch(await run("document.getElementById('generatedPlacementGuide').textContent"), /nodejs|package-lock/);
  assert.match(await run("document.getElementById('guideStartup').textContent"), /up --build/);
  assert.doesNotMatch(await run("document.getElementById('guideSecurity').textContent"), /Node.js|nodejs/);
  await run("window.__rendererUI.clearResultsOnly()");
  assert.equal(await run("document.getElementById('generationGuideButton').disabled"), true);
  assert.equal(await run("document.getElementById('generatedPlacementGuide').textContent"), "");
  console.log("PASS guide generation snapshot, manual edit/individual clear notices, re-generation and full clear remove stale content");

  await run("document.querySelector('.module-row[data-module-id=nodejs]').click(); window.__testConfirmModules(); window.__rendererGenerate.generateConfigs(); document.getElementById('generationGuideButton').click()");
  const screenshots = process.env.DOCKER_BUILDER_SCREENSHOT_DIR;
  const luminance = color => color.match(/[\d.]+/g).slice(0, 3).map(Number).map(v => { v /= 255; return v <= .04045 ? v / 12.92 : ((v + .055) / 1.055) ** 2.4; }).reduce((total, v, n) => total + v * [.2126, .7152, .0722][n], 0);
  for (const themeName of ["system", "light", "dark", "blue", "green", "yellow", "orange", "red", "pink"]) {
    await run(`window.__rendererCore.applyTheme('${themeName}')`);
    await run("new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))");
    const style = await run("(()=>{const p=getComputedStyle(document.getElementById('guideScrollBody'));const d=getComputedStyle(document.getElementById('generationGuideDialog'));return {font:parseFloat(p.fontSize),fg:p.color,bg:d.backgroundColor}})()");
    assert.ok(style.font >= 14);
    const a = luminance(style.fg), b = luminance(style.bg);
    assert.ok((Math.max(a, b) + .05) / (Math.min(a, b) + .05) >= 4.5, themeName);
    if (screenshots && ["light", "dark", "blue"].includes(themeName)) fs.writeFileSync(path.join(screenshots, `guide-${themeName}.png`), (await wc.capturePage()).toPNG());
  }
  win.setSize(720, 800);
  await run("new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))");
  assert.equal(await run("document.getElementById('generationGuideDialog').getBoundingClientRect().right <= innerWidth"), true);
  assert.equal(await run("document.getElementById('guideScrollBody').scrollWidth <= document.getElementById('guideScrollBody').clientWidth"), true);
  if (screenshots) fs.writeFileSync(path.join(screenshots, "guide-narrow.png"), (await wc.capturePage()).toPNG());
  win.setSize(1280, 800);
  await run("document.getElementById('generationGuideCloseButton').click(); window.__rendererUI.clearResultsOnly()");
  console.log("PASS guide font >=14px, nine themes contrast and narrow scrolling layout; screenshots captured");
};
